const { chromium } = require("playwright");
const http = require("node:http");
const fs = require("node:fs");
const path = require("node:path");
const root = path.resolve(__dirname, "..");
const types = { ".html":"text/html", ".css":"text/css", ".js":"text/javascript", ".png":"image/png" };
const server = http.createServer((req,res) => {
  const pathname = decodeURIComponent(new URL(req.url,"http://localhost").pathname);
  const file = path.resolve(root, pathname === "/" ? "index.html" : "." + pathname);
  if (!file.startsWith(root + path.sep) && file !== root) { res.writeHead(403).end(); return; }
  fs.readFile(file, (err, data) => {
    if (err) { res.writeHead(404).end(); return; }
    res.writeHead(200, {"Content-Type":types[path.extname(file)] || "application/octet-stream"}).end(data);
  });
});
(async () => {
  await new Promise(resolve => server.listen(4173,"127.0.0.1",resolve));
  const browser = await chromium.launch({headless:true});
  const page = await browser.newPage({viewport:{width:1440,height:1000}, deviceScaleFactor:1});
  const errors=[];
  page.on("pageerror", e => errors.push(e.message));
  await page.goto("http://127.0.0.1:4173/", {waitUntil:"networkidle"});
  await page.screenshot({path:"artifacts/countdown-desktop.png",fullPage:true});
  await page.getByRole("button",{name:"Add a date"}).click();
  await page.getByLabel("What are you counting down to?").fill("Seeing Tommy again");
  await page.getByLabel("When is it?").fill("2027-06-01T12:00");
  await page.getByRole("button",{name:"Save countdown"}).click();
  await page.getByText("Seeing Tommy again").first().waitFor();
  if (!new URL(page.url()).searchParams.has("at")) throw new Error("Active countdown should be reflected in the URL.");
  if (!new URL(page.url()).searchParams.has("since")) throw new Error("Share URL should preserve the journey start.");
  await page.getByRole("button",{name:"Edit countdown"}).click();
  await page.getByLabel("What are you counting down to?").fill("Our summer trip");
  await page.getByLabel("When is it?").fill("2027-07-04T09:30");
  await page.getByRole("button",{name:"Save changes"}).click();
  await page.getByText("Our summer trip").first().waitFor();
  if (new URL(page.url()).searchParams.get("name") !== "Our summer trip") throw new Error("Editing should update the share URL.");
  await page.getByRole("button",{name:"Share"}).waitFor();
  await page.locator("#countdown-format").selectOption("minutes");
  await page.getByLabel("First city").selectOption("Asia/Tokyo");
  await page.getByLabel("Second city").selectOption("Europe/London");
  await page.getByLabel("Journey bar").uncheck();
  await page.getByLabel("Sky artwork").selectOption("line");
  await page.locator("#clock-left").waitFor();
  if (await page.locator("#journey").isVisible()) throw new Error("Journey bar should be hidden when switched off.");
  if (await page.locator("#count-days").isVisible()) throw new Error("Days should be hidden in minutes mode.");
  if (await page.locator("#count-hours").isVisible()) throw new Error("Hours should be hidden in minutes mode.");
  if (!(await page.locator("#count-minutes").isVisible())) throw new Error("Minutes display should remain visible.");
  await page.screenshot({path:"artifacts/countdown-created-desktop.png",fullPage:true});
  const link = new URL(page.url());
  const createdAtBeforeReload=await page.evaluate(()=>JSON.parse(localStorage.getItem("countdown.timers.v2"))[0].createdAt);
  await page.reload();
  await page.getByText("Our summer trip").first().waitFor();
  const createdAtAfterReload=await page.evaluate(()=>JSON.parse(localStorage.getItem("countdown.timers.v2"))[0].createdAt);
  if(createdAtBeforeReload!==createdAtAfterReload)throw new Error("Reloading a shared URL must not reset journey progress.");
  await page.getByRole("button",{name:"Edit countdown"}).click();
  await page.getByLabel("When is it?").fill("2020-01-01T00:00");
  await page.getByRole("button",{name:"Save changes"}).click();
  await page.locator("#arrival-message").waitFor({state:"visible"});
  if (await page.locator("#time-grid").isVisible()) throw new Error("Arrived countdown should replace the ticking timer.");
  await page.screenshot({path:"artifacts/countdown-arrived-desktop.png",fullPage:true});
  if (await page.locator("#city-left").inputValue() !== "Asia/Tokyo") throw new Error("City preference did not persist.");
  if (await page.locator("#countdown-format").inputValue() !== "minutes") throw new Error("Countdown precision did not persist.");
  const legacy=await browser.newPage({viewport:{width:1280,height:800}});
  await legacy.goto("http://127.0.0.1:4173/?countdowndate=2027-06-01",{waitUntil:"networkidle"});
  if(await legacy.locator("#journey").isVisible())throw new Error("Legacy links without a known start must not invent journey progress.");
  const mobile = await browser.newPage({viewport:{width:390,height:844},deviceScaleFactor:1,isMobile:true,hasTouch:true});
  await mobile.goto("http://127.0.0.1:4173/",{waitUntil:"networkidle"});
  await mobile.getByRole("button",{name:"Create your first countdown"}).click();
  await mobile.getByLabel("What are you counting down to?").fill("A weekend away");
  await mobile.getByLabel("When is it?").fill("2027-08-01T10:00");
  await mobile.getByRole("button",{name:"Save countdown"}).click();
  await mobile.getByText("A weekend away").first().waitFor();
  const widths=await mobile.evaluate(()=>({client:document.documentElement.clientWidth,scroll:document.documentElement.scrollWidth}));
  if(widths.scroll>widths.client)throw new Error("Mobile layout overflows horizontally: "+JSON.stringify(widths));
  await mobile.screenshot({path:"artifacts/countdown-mobile.png",fullPage:true});
  if(errors.length) throw new Error(errors.join("\n"));
  await browser.close();
  await new Promise(resolve=>server.close(resolve));
})().catch(async e=>{ console.error(e); server.close(); process.exit(1); });
